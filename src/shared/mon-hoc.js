const BY_MAPPING = new Map();
for (const row of MON_HOC) {
  const code = String(row.mapping_code || '').trim();
  if (!code || BY_MAPPING.has(code)) continue;
  BY_MAPPING.set(code, {
    name: String(row.name || '').trim(),
    moet_code: String(row.moet_code || '').trim(),
  });
}

export function monHocMappingOptions() {
  return [...BY_MAPPING.entries()].map(([code, row]) => ({
    value: code,
    label: row.name ? `${row.name} - [${code}]` : `[${code}]`,
  }));
}

export function monHocMappingCodes() {
  return [...BY_MAPPING.keys()];
}

export function moetCodeFromMapping(mappingCode) {
  return BY_MAPPING.get(String(mappingCode || '').trim())?.moet_code || '';
}

/** Đổi maMonHoc trong request KQHT từ mapping_code CSDL sang moet_code cho SMIS. */
export function applySmisMonHoc(built) {
  if (!built?.ok) return built;
  const code = String(built.body?.maMonHoc || '').trim();
  if (!code) return built;
  if (BY_MAPPING.has(code)) {
    const moet = moetCodeFromMapping(code);
    if (!moet) {
      return {
        ok: false,
        error: 'kqht_mon_moet_missing',
        data: { detail: `Môn ${code} chưa có mã MOET để gửi SMIS.` },
      };
    }
    return { ...built, body: { ...built.body, maMonHoc: moet } };
  }
  // Đã là moet_code (ví dụ filter đã đổi sẵn) thì giữ nguyên.
  if ([...BY_MAPPING.values()].some((row) => row.moet_code === code)) return built;
  return {
    ok: false,
    error: 'kqht_mon_invalid',
    data: { detail: `Mã môn ${code} không có trong danh mục CSDL ngành.` },
  };
}

export default MON_HOC;